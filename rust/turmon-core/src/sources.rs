#[derive(Clone, Copy)]
pub enum Sample {
    I(i64),
    F(f64),
    S(&'static str),
}

pub fn sample_values() -> Values {
    SOURCES.iter().map(|(k, _, _, _, _, s)| (k.to_string(), match s {
        Sample::I(i) => Val::Int(*i),
        Sample::F(f) => Val::Num(*f),
        Sample::S(t) => Val::Str(t.to_string()),
    })).collect()
}
